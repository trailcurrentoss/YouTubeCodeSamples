/*
 * JD9855 power-on register sequence.
 *
 * TRANSCRIBED VERBATIM from LovyanGFX Panel_ST77961::getInitCommands(),
 * list0[] — github.com/lovyan03/LovyanGFX,
 * src/lgfx/v1/panel/Panel_ST77961.hpp. That is the sequence Elecrow's own
 * firmware runs on this panel.
 *
 * LovyanGFX encodes the table as {cmd, count, params...} with a 0x80 flag on
 * count meaning "a delay byte follows the parameters". That has been unpacked
 * here into an explicit delay_ms field rather than reproducing the flag, so
 * the table can be walked with a plain loop.
 *
 * Two entries are worth knowing about:
 *   0x2A / 0x2B (CASET / RASET) are set to 0x0000..0x0167, i.e. 0..359. The
 *   panel is 360x360. LovyanGFX's Panel_ST77961 CONSTRUCTOR defaults to
 *   360x390, which is wrong for this board -- the init table is the correct
 *   authority and Elecrow overrides the constructor to match it.
 *
 *   0x3A = 0x05 selects RGB565.
 */
#pragma once

#include <stdint.h>

typedef struct {
    uint8_t  cmd;
    uint8_t  len;          /* number of valid bytes in data[] */
    uint8_t  data[32];
    uint16_t delay_ms;     /* 0 = no delay after this command */
} jd9855_init_cmd_t;

