/** Look up a key in the chosen language, falling back to English. */
function makeTranslator(code) {
  const table = STRINGS[code] || STRINGS.en;
  const extra = EXTRA[code] || EXTRA.en;
  const outputState = OUTPUT_STATE[code] || OUTPUT_STATE.en;
  return (key) =>
    outputState[key] ??
    table[key] ??
    extra[key] ??
    EXTRA.en[key] ??
    STRINGS.en[key] ??
    key;
}

